#!/usr/bin/env python3
"""Write registry/models.audited.yaml from a local models.yaml.

The tracked file is the audit copy of the gate's inputs (models, run
settings, settings_checked, price blocks, public provider settings).
Recorded values are copied unchanged. Literal api_key values and
machine-only URLs (loopback, tailnet, RFC1918) stay in the gitignored
models.yaml and are not written here.

The tracked name is models.audited.yaml, NOT models.yaml: the scrub rule
"(^|/)models[.]yaml$" refuses the operator's live registry outright (it
holds real endpoints and api_key_env names), and the audited copy is a
different file with a different meaning. models.example.yaml is the blank
template users copy; the audited copy is what was actually recorded.

Usage: python3 scripts/export_settings_registry.py [path/to/models.yaml]
"""
from __future__ import annotations

import ipaddress
import re
import sys
from pathlib import Path
from urllib.parse import urlparse

import yaml

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "registry" / "models.audited.yaml"
ENV_REF = re.compile(r"^\$\{?[A-Z][A-Z0-9_]*\}?$")
PUBLIC_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def _host(url: str) -> str:
    try:
        return (urlparse(url).hostname or "").lower()
    except ValueError:
        return ""


def machine_url(url: str) -> bool:
    host = _host(url)
    if not host or host in ("localhost",) or host.endswith(".local"):
        return True
    try:
        ip = ipaddress.ip_address(host)
    except ValueError:
        return False
    # CGNAT (100.64/10, the tailnet) is not is_private. Any non-global address is machine-only.
    return not ip.is_global


def _strip_provider(name: str, prov: dict) -> dict:
    out = {}
    for key, val in prov.items():
        if key == "api_key":
            continue
        if isinstance(val, str) and val.startswith(("http://", "https://")) and machine_url(val):
            continue
        if key == "headers" and isinstance(val, dict):
            kept = {}
            for hk, hv in val.items():
                if isinstance(hv, str) and (ENV_REF.match(hv) or PUBLIC_DATE.match(hv)):
                    kept[hk] = hv
            if kept:
                out[key] = kept
            continue
        out[key] = val
    if "type" not in out:
        raise SystemExit(f"provider {name} lost its type while stripping")
    return out


def _walk_forbidden(node, path: str) -> None:
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "api_key":
                raise SystemExit(f"refusing to write api_key at {path}.{k}")
            _walk_forbidden(v, f"{path}.{k}")
    elif isinstance(node, list):
        for i, v in enumerate(node):
            _walk_forbidden(v, f"{path}[{i}]")
    elif isinstance(node, str) and node.startswith(("http://", "https://")) and machine_url(node):
        raise SystemExit(f"refusing to write a machine URL at {path}")


def export(src: Path) -> None:
    live = yaml.safe_load(src.read_text(encoding="utf-8"))
    if not isinstance(live, dict):
        raise SystemExit("models.yaml is not a mapping")
    out = {
        "defaults": live.get("defaults"),
        "judge": live.get("judge"),
        # tags name the operator's machines. They are not a gate input and
        # the personal scrub rules refuse them. Every other model field,
        # including settings_checked, is copied unchanged.
        "models": [{k: v for k, v in m.items() if k != "tags"} if isinstance(m, dict) else m
                   for m in (live.get("models") or [])],
        "providers": {n: _strip_provider(n, p) for n, p in (live.get("providers") or {}).items()},
    }
    _walk_forbidden(out, "registry")
    live_sc = {m["name"]: m.get("settings_checked") for m in live.get("models") or []
               if isinstance(m, dict) and m.get("settings_checked")}
    copy_sc = {m["name"]: m.get("settings_checked") for m in out["models"] or []
               if isinstance(m, dict) and m.get("settings_checked")}
    if live_sc != copy_sc:
        raise SystemExit("settings_checked values changed; not writing")
    if len(live_sc) < 1:
        raise SystemExit("no settings_checked records in the source")
    DEST.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Audited registry. Generated by scripts/export_settings_registry.py.\n"
        "# settings_checked and the other model fields are the recorded values.\n"
        "# Omitted: tags, literal api_key values, and machine-only URLs.\n"
        "# Those stay in the gitignored models.yaml.\n"
    )
    body = yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=1000)
    DEST.write_text(header + body, encoding="utf-8")
    print(f"wrote {DEST} settings_checked={len(copy_sc)} models={len(out['models'])}")


if __name__ == "__main__":
    export(Path(sys.argv[1]).expanduser() if len(sys.argv) > 1
           else Path.home() / "Projects" / "crucibleforge" / "models.yaml")
